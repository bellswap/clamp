// Copies the contract ABIs the service and the site use from contracts/out (forge build output) into generated
// TypeScript modules, so both consumers build against the compiled contracts, not hand-written signatures.
//   bun run scripts/abi.ts            forge build in contracts/, then write the modules
//   bun run scripts/abi.ts --no-build  use contracts/out as it is
//   bun run scripts/abi.ts --check     exit 1 when a generated module differs from contracts/out (CI drift check)
// Output: services/bell/src/abi/<Name>.ts and site/src/abi/<Name>.ts, each `export default [...] as const`.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const out = resolve(root, 'contracts/out');
const targets: Record<string, string[]> = {
  'services/bell/src/abi': ['TicketBook', 'HouseVault', 'DemoSignerReference'],
  'site/src/abi': ['TicketBook', 'HouseVault', 'DemoSignerReference'],
};
const check = process.argv.includes('--check');

if (!check && !process.argv.includes('--no-build')) {
  const r = Bun.spawnSync(['forge', 'build'], { cwd: resolve(root, 'contracts'), stdout: 'inherit', stderr: 'inherit' });
  if (r.exitCode !== 0) process.exit(r.exitCode ?? 1);
}

function render(name: string): string {
  const f = resolve(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(f)) throw new Error(`missing ${f} (run forge build in contracts/)`);
  const abi = JSON.parse(readFileSync(f, 'utf8')).abi;
  if (!Array.isArray(abi) || abi.length === 0) throw new Error(`empty ABI in ${f}`);
  return `// Generated by scripts/abi.ts from contracts/out/${name}.sol/${name}.json. Do not edit; rerun the script.\n` +
    `export default ${JSON.stringify(abi, null, 2)} as const;\n`;
}

let drift = 0;
for (const [dir, names] of Object.entries(targets)) {
  const abs = resolve(root, dir);
  if (!check) mkdirSync(abs, { recursive: true });
  for (const name of names) {
    const text = render(name);
    const dest = resolve(abs, `${name}.ts`);
    if (check) {
      const same = existsSync(dest) && readFileSync(dest, 'utf8') === text;
      if (!same) { drift++; console.log(`drift: ${dir}/${name}.ts`); }
    } else {
      writeFileSync(dest, text);
      console.log(`wrote ${dir}/${name}.ts`);
    }
  }
}
process.exit(drift ? 1 : 0);
