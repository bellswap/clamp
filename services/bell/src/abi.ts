// Contract ABIs. The service uses the ABIs generated from contracts/out by scripts/abi.ts (src/abi/<Name>.ts).
// The minimal ABIs below, written from docs/INTERFACES.md, are kept for tests and as a reference of what the
// service calls; the service reads event arguments by name and accepts the usual spelling variants.
import { parseAbi, type Abi } from 'viem';
import TicketBookAbi from './abi/TicketBook';
import HouseVaultAbi from './abi/HouseVault';
import DemoSignerReferenceAbi from './abi/DemoSignerReference';

export const MIN_TICKET_BOOK = parseAbi([
  'event MarketListed(bytes32 indexed symbol, address source, uint8 maxLeverage, uint256 maxStake, uint256 oiCap, uint64 maxStaleness)',
  'event TicketOpened(uint256 indexed id, address indexed owner, bytes32 indexed symbol, bool long, uint8 leverage, uint256 stake, uint256 entryPrice8, uint64 expiry)',
  'event TicketSettled(uint256 indexed id, uint256 settlePrice8, uint256 payout)',
  'event FeeSet(uint16 feeBps)',
  'function open(bytes32 symbol, bool long, uint8 leverage, uint256 stake, uint8 horizon) returns (uint256 id)',
  'function settle(uint256 id, bytes proof)',
  'function listMarket(bytes32 symbol, address source, uint8 maxLeverage, uint256 maxStake, uint256 oiCap, uint64 maxStaleness)',
  'function feeBps() view returns (uint256)',
]);

export const MIN_HOUSE_VAULT = parseAbi([
  'event Deposit(address indexed sender, address indexed owner, uint256 assets, uint256 shares)',
  'event Withdraw(address indexed sender, address indexed receiver, address indexed owner, uint256 assets, uint256 shares)',
  'event Transfer(address indexed from, address indexed to, uint256 value)',
  'event Reserved(uint256 amount, uint256 totalReserved)',
  'event Released(uint256 amount, uint256 totalReserved)',
  'function totalAssets() view returns (uint256)',
  'function reserved() view returns (uint256)',
  'function free() view returns (uint256)',
  'function totalSupply() view returns (uint256)',
]);

export const MIN_DEMO_SIGNER = parseAbi([
  'function post(bytes32 symbol, uint256 price8, uint64 timestamp, bytes signature)',
  'function postMany(bytes32[] symbols, uint256[] prices8, uint64[] timestamps, bytes[] signatures)',
  'function latest(bytes32 symbol) view returns (uint256 price8, uint64 timestamp, uint8 tier)',
  'function signer() view returns (address)',
]);

export const ERC20 = parseAbi([
  'function transfer(address to, uint256 amount) returns (bool)',
  'function balanceOf(address owner) view returns (uint256)',
  'function allowance(address owner, address spender) view returns (uint256)',
  'function decimals() view returns (uint8)',
]);

export const abis = {
  book: TicketBookAbi as unknown as Abi,
  vault: HouseVaultAbi as unknown as Abi,
  signer: DemoSignerReferenceAbi as unknown as Abi,
};
